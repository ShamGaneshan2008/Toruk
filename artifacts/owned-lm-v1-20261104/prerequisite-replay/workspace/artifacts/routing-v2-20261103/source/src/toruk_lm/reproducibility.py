def read_object(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise ValueError(f"invalid JSON in {path}: {error.msg}") from error
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object in {path}")
    return value


def validate_config(path: Path) -> dict[str, Any]:
    config = read_object(path)
    keys = {"schema", "mode", "seed", "fixture_seed", "steps", "worlds", "answer_budget", "seconds"}
    if set(config) != keys or config["schema"] != "toruk-reproduce-v1":
        raise ValueError("reproduction config requires exactly: " + ", ".join(sorted(keys)))
    if config["mode"] not in ("smoke", "primary"):
        raise ValueError("config mode must be smoke or primary")
    expected = (2, 2, 2) if config["mode"] == "smoke" else (12, 4, 16)
    for name, value in zip(("steps", "worlds", "answer_budget"), expected, strict=True):
        if type(config[name]) is not int or config[name] != value:
            raise ValueError(f"{config['mode']} v1 requires {name}={value}")
    if any(
        type(config[k]) is not int or config[k] != v
        for k, v in (("seed", 23), ("fixture_seed", 17))
    ):
        raise ValueError("v1 reproduction freezes seed=23 and fixture_seed=17")
    seconds = config["seconds"]
    if type(seconds) not in (int, float) or not math.isfinite(seconds) or not 0 < seconds <= 110:
        raise ValueError("seconds must be finite and in (0, 110]")
    return config


def verify_files(directory: Path) -> int:
    manifest = read_object(directory / "manifest.json")
    files = manifest.get("files")
    if not isinstance(files, dict) or not files:
        raise ValueError(f"missing file hashes in {directory}/manifest.json")
    for name, digest in files.items():
        path = (directory / name).resolve()
        if not path.is_relative_to(directory.resolve()):
            raise ValueError(f"manifest path escapes its directory: {name}")
        if not path.is_file():
            raise ValueError(f"missing artifact {path}; restore the recorded local artifact")
        if sha256_file(path) != digest:
            raise ValueError(f"artifact checksum mismatch: {path}")
    return len(files)


def rescore(
    predictions: list[dict[str, Any]], rows: list[dict[str, Any]], budget: int
) -> dict[str, Any]:
    probes = {(r["id"], p["question"]): p for r in rows for p in r["probes"]}
    seen = set()
    for prediction in predictions:
        key = prediction["world_id"], prediction["question"]
        if key in seen or key not in probes:
            raise ValueError("duplicate or unexpected prediction world/question")
        seen.add(key)
        probe = probes[key]
        ids = prediction["generated_ids"]
        if not isinstance(ids, list) or not 0 < len(ids) <= budget:
            raise ValueError("generated token count exceeds frozen budget or is empty")
        if any(type(token) is not int or not 2 <= token < 259 for token in ids):
            raise ValueError("invalid generated byte-token IDs")
        if 2 in ids[:-1]:
            raise ValueError("generation continued after EOS")
        decoded = ByteTokenizer().decode(ids)
        answer = decoded.split("\n", 1)[0]
        if (
            prediction["generated"] != decoded
            or prediction["answer"] != answer
            or prediction["gold"] != probe["answer"]
            or prediction["group"] != probe["group"]
            or type(prediction["correct"]) is not bool
            or prediction["correct"] != (answer == probe["answer"])
        ):
            raise ValueError("prediction text, oracle label or correctness mismatch")
    if seen != set(probes):
        raise ValueError("missing prediction world/question")
    return summarize(predictions)


def score_directory(directory: Path, rows: list[dict[str, Any]], budget: int) -> dict[str, Any]:
    predictions = json.loads((directory / "predictions.json").read_text(encoding="utf-8"))
    quality = rescore(predictions, rows, budget)
    metrics = read_object(directory / "metrics.json")
    for key, value in quality.items():
        if metrics[key] != value:
            raise ValueError(f"stored metric {key} disagrees with raw outputs: {directory}")
    return quality


def audit_evidence(
    parent: Path, handoff: Path, studies: list[Path], output: Path
) -> dict[str, Any]:
    """Audit historical seals without substituting today's code hash for archived identity."""
    fresh(output)
    summary = parent_integrity(parent, handoff)
    entries = verify_files(parent)
    validation = load_worlds(parent / "data/validation.jsonl", "validation")
    training = load_worlds(parent / "data/train.jsonl", "train")
    entities = [
        {e["entity"] for r in split for e in r["events"]} for split in (training, validation)
    ]
    if entities[0] & entities[1]:
        raise ValueError("train/validation entity overlap")
    table: list[dict[str, Any]] = []
    checkpoints = {}
    for name, trained in summary["training"].items():
        path = parent / name / "checkpoint.pt"
        _, saved = load_controlled(path)
        if (
            sha256_file(path) != trained["checkpoint_sha256"]
            or saved["config"] != trained["config"]
            or saved["data"] != trained["data"]
            or saved["next_step"] != trained["total_steps"]
            or saved["data"]
            != {s: dataset_identity(parent / f"data/{s}.jsonl") for s in ("train", "validation")}
        ):
            raise ValueError(f"checkpoint/config/data identity mismatch: {path}")
        checkpoints[name] = dict(
            path=path.as_posix(),
            sha256=sha256_file(path),
            config=saved["config"],
            tokenizer=saved["tokenizer"],
            package_sha256=saved["package_sha256"],
            boundary=saved["boundary"],
            next_step=saved["next_step"],
            data=saved["data"],
        )
    for path in sorted(parent.glob("*-labels-*/labels.json")):
        labels = read_object(path)
        payload = {key: labels[key] for key in ("features", "labels")}
        digest = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
        identity = labels["identity"]
        if digest != labels["payload_sha256"] or identity["split"] not in ("train", "validation"):
            raise ValueError(f"paired-label checksum/split mismatch: {path}")
        if identity["checkpoint_sha256"] not in {c["sha256"] for c in checkpoints.values()}:
            raise ValueError(f"unbound paired labels: {path}")
        if identity["data"] != dataset_identity(parent / f"data/{identity['split']}.jsonl"):
            raise ValueError(f"paired-label data identity mismatch: {path}")
        if (
            identity["code"] != read_object(parent / "protocol.json")["package_sha256"]
            or identity["answer_budget"] != 16
        ):
            raise ValueError(f"paired-label code/budget mismatch: {path}")
    bindings = model_bindings(parent, summary)
    for name, binding in bindings.items():
        verify_binding(parent, binding)
        metrics = read_object(parent / name / "metrics.json")
        if (
            metrics["config"] != binding["training"]["config"]
            or metrics["checkpoint_sha256"] != binding["checkpoint_sha256"]
        ):
            raise ValueError(f"M6 evaluation checkpoint/config mismatch: {name}")
        if binding["predictor"]:
            saved_predictor = torch.load(parent / binding["predictor"], weights_only=True)
            metadata = saved_predictor["metadata"]
            labels = parent / (binding["checkpoint"].split("/")[0] + "-labels-train/labels.json")
            if metadata["checkpoint_sha256"] != binding["checkpoint_sha256"] or metadata[
                "training_labels_sha256"
            ] != sha256_file(labels):
                raise ValueError(f"predictor training lineage mismatch: {name}")

    def append(
        study: str,
        cell: str,
        name: str,
        directory: Path,
        rows: list[dict[str, Any]],
        budget: int,
        protocol: Path,
    ) -> None:
        quality = score_directory(directory, rows, budget)
        metrics = read_object(directory / "metrics.json")
        primary = sum(quality["groups"][g]["accuracy"] for g in KNOWN_GROUPS) / 4
        table.append(
            dict(
                study=study,
                cell=cell,
                method=name,
                examples=quality["examples"],
                primary=primary,
                exact_accuracy=quality["exact_accuracy"],
                answer_coverage=quality["answer_coverage"],
                inference_seconds=metrics["inference_seconds"],
                inference_forward_tokens=metrics["inference_forward_tokens"],
                predictor_fallbacks=metrics["predictor_fallbacks"],
                final_boundaries=metrics["final_boundaries"],
                predictions=(directory / "predictions.json").as_posix(),
                predictions_sha256=sha256_file(directory / "predictions.json"),
                protocol=protocol.as_posix(),
                protocol_sha256=sha256_file(protocol),
                checkpoint_sha256=metrics["checkpoint_sha256"],
                training_seed=metrics["config"]["seed"],
                source_package_sha256=metrics["package_sha256"],
            )
        )
        if metrics["data"] != dataset_identity(
            (parent / "data/validation.jsonl")
            if study == "M6"
            else directory.parents[1] / "data" / cell / "validation.jsonl"
        ):
            raise ValueError(f"evaluation data identity mismatch: {directory}")

    for name in sorted(EXPECTED_RESULTS):
        append("M6", "validation", name, parent / name, validation, 16, parent / "protocol.json")
    for study in studies:
        entries += verify_files(study)
        protocol_path = study / "protocol.json"
        protocol = read_object(protocol_path)
        which = protocol["study"]
        expected_cells = (
            ("control", "template4", "template5")
            if which == "templates"
            else ("control", "claims4", "claims12", "facts4", "facts12")
        )
        if (
            which not in METHODS
            or set(protocol["cells"]) != set(expected_cells)
            or set(protocol["methods"]) != set(METHODS[which])
        ):
            raise ValueError("incomplete or unsupported frozen study")
        if protocol["kernel"] != kernel_identity():
            raise ValueError("study kernel mismatch")
        if (
            protocol["answer_budget"] != 16
            or protocol["training_seeds"] != [23]
            or protocol["final_test"] != "closed"
            or protocol["anchors"] != [[117, 40], [117, 41], [118, 50], [118, 51]]
            or protocol["new_training_steps"] != 0
            or protocol["parent_manifest_sha256"] != sha256_file(parent / "manifest.json")
        ):
            raise ValueError("study generation/seeds/test policy mismatch")
        stored = read_object(study / "summary.json")
        if stored["protocol_sha256"] != sha256_file(protocol_path) or set(stored["results"]) != set(
            expected_cells
        ):
            raise ValueError("study summary/protocol mismatch")
        for cell in expected_cells:
            if protocol["cells"][cell] != CELLS[cell] or set(stored["results"][cell]) != set(
                METHODS[which]
            ):
                raise ValueError("study cell/config/method mismatch")
            data = study / "data" / cell / "validation.jsonl"
            rows = load_worlds(data, "validation")
            manifest = read_object(data.parent / "manifest.json")
            if not manifest.get("evaluation_only") or manifest["protocol_sha256"] != sha256_file(
                protocol_path
            ):
                raise ValueError("held-out data missing protocol/training prohibition")
            if rows != [
                shift_world(seed, index, cell, CELLS[cell]) for seed, index in protocol["anchors"]
            ]:
                raise ValueError("held-out anchors/transformations mismatch")
            for row in rows:
                check_holdout(row, training + validation)
            for method, binding in protocol["methods"].items():
                verify_binding(parent, binding)
                directory = study / cell / method
                append(which, cell, method, directory, rows, 16, protocol_path)
                predictions = json.loads(
                    (directory / "predictions.json").read_text(encoding="utf-8")
                )
                analysis = describe(predictions, rows)
                for key, value in analysis.items():
                    if stored["results"][cell][method][key] != value:
                        raise ValueError(f"study summary rescore mismatch: {directory}/{key}")
                metrics = read_object(directory / "metrics.json")
                if (
                    metrics["config"] != binding["training"]["config"]
                    or metrics["checkpoint_sha256"] != binding["checkpoint_sha256"]
                    or metrics["predictor_sha256"] != binding["predictor_sha256"]
                ):
                    raise ValueError("study evaluation checkpoint/config/predictor mismatch")
    with (output / "results.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(table[0]))
        writer.writeheader()
        writer.writerows(table)
    lines = [
        "| Study | Cell | Method | N | Known-fact macro | Overall |",
        "| --- | --- | --- | ---: | ---: | ---: |",
    ]
    lines += [
        f"| {r['study']} | {r['cell']} | {r['method']} | {r['examples']} | "
        f"{r['primary']:.3%} | {r['exact_accuracy']:.3%} |"
        for r in table
    ]
    (output / "tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    report = dict(
        schema="toruk-evidence-audit-v1",
        status="PASS",
        operation="historical integrity and independent rescoring; no new model generation",
        historical_manifest_entries=entries,
        results=table,
        checkpoints=checkpoints,
        reproduction="NOT_REPRODUCED by this command; use recorded replay/reproduction runs",
        inherited_M6_cost=summary["cost"],
        final_test=(
            "this audit hashes test bytes only; no model scoring; "
            "unit-test label access is disclosed in the M8 research audit"
        ),
        training_seed_uncertainty=None,
        audit_package_sha256=package_fingerprint(),
    )
    write_json(output / "audit.json", report)
    return dict(
        status="PASS",
        results=len(table),
        answers=sum(r["examples"] for r in table),
        evidence=str(output),
    )


def compare_replay(reference: Path, reproduction: Path, output: Path) -> dict[str, Any]:
    """Require exact generated IDs and score parity; timing is deliberately excluded."""
    paths = sorted(p.relative_to(reference) for p in reference.rglob("predictions.json"))
    actual = sorted(p.relative_to(reproduction) for p in reproduction.rglob("predictions.json"))
    if not paths or paths != actual:
        raise ValueError("replay prediction files missing, extra or incomplete")
    keys = ("world_id", "group", "question", "generated_ids", "answer", "gold", "correct")
    answers = 0
    hashes = {}
    for path in paths:
        left = json.loads((reference / path).read_text(encoding="utf-8"))
        right = json.loads((reproduction / path).read_text(encoding="utf-8"))
        if [{k: p[k] for k in keys} for p in left] != [{k: p[k] for k in keys} for p in right]:
            raise ValueError(f"replay generated-answer mismatch: {path}")
        metric = path.parent / "metrics.json"
        if (
            read_object(reference / metric)["groups"]
            != read_object(reproduction / metric)["groups"]
        ):
            raise ValueError(f"replay score mismatch: {metric}")
        answers += len(left)
        hashes[path.as_posix()] = {
            "reference": sha256_file(reference / path),
            "reproduction": sha256_file(reproduction / path),
        }
    fresh(output)
    result = dict(
        status="PASS",
        comparisons=len(paths),
        answers=answers,
        reference=str(reference),
        reproduction=str(reproduction),
        rule="exact generated IDs, answers, gold, groups and correctness; excludes timing",
        prediction_files=hashes,
    )
    write_json(output / "comparison.json", result)
    return {k: v for k, v in result.items() if k != "prediction_files"}


def reproduce(config_path: Path, output: Path) -> dict[str, Any]:
    config = validate_config(config_path)
    if config["mode"] == "primary":
        return run_pilot(
            output, config["steps"], config["worlds"], config["answer_budget"], config["seconds"]
        )
    fresh(output)
    write_json(output / "config.json", config)
    journal = Journal(output, config["seconds"])
    data = output / "data"
    journal.run("data", lambda: make_worlds(data, config["fixture_seed"], config["worlds"]))
    model_config = ModelConfig(width=8, heads=2, layers=1)
    results = {}
    for variant in ("ordinary", "recurrent"):
        fit = partial(
            train_controlled,
            data / "train.jsonl",
            data / "validation.jsonl",
            variant=variant,
            config=model_config,
        )
        journal.run(variant + "-full", partial(fit, output=output / (variant + "-full"), steps=2))
        journal.run(variant + "-part", partial(fit, output=output / (variant + "-part"), steps=1))
        journal.run(
            variant + "-resume",
            partial(
                fit,
                output=output / (variant + "-resume"),
                steps=2,
                resume=output / (variant + "-part") / "checkpoint.pt",
            ),
        )
        model, full = load_controlled(output / (variant + "-full") / "checkpoint.pt")
        _, resumed = load_controlled(output / (variant + "-resume") / "checkpoint.pt")
        for key, tensor in full["model"].items():
            if not torch.equal(tensor, resumed["model"][key]):
                raise ValueError("smoke resume weights differ from uninterrupted training")
        if (
            not torch.equal(full["torch_rng"], resumed["torch_rng"])
            or full["python_rng"] != resumed["python_rng"]
        ):
            raise ValueError("smoke resume RNG mismatch")
        if isinstance(model, RecurrentLM):
            with torch.no_grad():
                session = Session(model)
                session.consume([1, 10, 11])
                clone = session.clone()
                if clone.generate([12], 2) != session.generate([12], 2):
                    raise ValueError("stream clone generation mismatch")
                session.reset()
                if session.prefix or not torch.equal(session.memory, model.initial_state()):
                    raise ValueError("stream reset mismatch")
        else:
            generate(model, [1, 10], 2)
        directory = output / (variant + "-eval")
        metrics = journal.run(
            variant + "-evaluate",
            partial(
                evaluate_controlled,
                output / (variant + "-resume") / "checkpoint.pt",
                data / "validation.jsonl",
                directory,
                2,
            ),
        )
        score_directory(directory, load_worlds(data / "validation.jsonl", "validation"), 2)
        results[variant] = dict(
            groups=metrics["groups"], resume="PASS", checkpoint_sha256=metrics["checkpoint_sha256"]
        )
    record = dict(
        status="PASS",
        purpose="execution smoke; no research-quality claim",
        results=results,
        elapsed_seconds=time.perf_counter() - journal.started,
        cumulative_process_peak_bytes=process_peak_bytes(),
        package_sha256=package_fingerprint(),
        config_sha256=sha256_file(config_path),
    )
    write_json(output / "summary.json", record)
    write_json(
        output / "manifest.json",
        dict(
            files={
                p.relative_to(output).as_posix(): sha256_file(p)
                for p in sorted(output.rglob("*"))
                if p.is_file()
            }
        ),
    )
    return record
